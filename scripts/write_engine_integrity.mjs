#!/usr/bin/env node
// The committed per-engine manifests are the decoded-byte source of truth.
// No engine binaries or network requests are needed to regenerate this module.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const REPRESENTATIONS = 'scripts/engine_artifact_representations.json';
export const OUTPUT = 'src/lc0/engineArtifactPins.generated.ts';
export function enginePins(root = ROOT) {
  const pins = {};
  for (const engine of ['berserk', 'plentychess', 'reckless', 'stockfish', 'stormphrax', 'viridithas']) {
    const dir = `public/${engine}`;
    const manifests = readdirSync(join(root, dir)).filter((name) => name.endsWith('.manifest.json'));
    if (manifests.length !== 1) throw new Error(`Expected one engine manifest in ${dir}`);
    const manifest = JSON.parse(readFileSync(join(root, dir, manifests[0]), 'utf8'));
    for (const artifact of manifest.artifacts) {
      if (!/\.(?:js|wasm|data|nnue)$/.test(artifact.path)) continue;
      if (artifact.missing || !/^[a-f0-9]{64}$/.test(artifact.sha256) || !Number.isSafeInteger(artifact.bytes) || artifact.bytes <= 0) {
        throw new Error(`Missing integrity pin: ${artifact.path}`);
      }
      const path = artifact.path.replace(/^public/, '');
      pins[path] = { sha256: artifact.sha256, bytes: artifact.bytes };
    }
  }
  const release = JSON.parse(readFileSync(join(root, REPRESENTATIONS), 'utf8'));
  for (const [path, entry] of Object.entries(release.artifacts)) {
    const pin = pins[path];
    if (!pin) throw new Error(`Release artifact has no manifest pin: ${path}`);
    if (pin.sha256 !== entry.raw.sha256 || pin.bytes !== entry.raw.bytes)
      throw new Error(`Release/engine manifest mismatch: ${path}; refresh the representation snapshot with --release`);
    const br = entry.br;
    if (br) {
      if (!/^[a-f0-9]{64}$/.test(br.sha256) || !Number.isSafeInteger(br.bytes) || br.bytes <= 0) throw new Error(`Invalid Brotli representation: ${path}`);
      pin.br = br.sha256;
    }
  }
  return Object.fromEntries(Object.entries(pins).sort(([a], [b]) => a.localeCompare(b)));
}
export function serializePins(pins) {
  return `// Generated by scripts/write_engine_integrity.mjs; do not edit.\nexport const ENGINE_ARTIFACT_PINS = {\n${Object.entries(pins)
    .map(([path, pin]) => `  '${path}': {\n    sha256: '${pin.sha256}',\n    bytes: ${pin.bytes},\n${pin.br ? `    br: '${pin.br}',\n` : ''}  },`)
    .join('\n')}\n} as const;\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const releaseIndex = process.argv.indexOf('--release');
  if (releaseIndex !== -1) {
    const path = process.argv[releaseIndex + 1];
    const release = JSON.parse(readFileSync(path, 'utf8'));
    if (release.schema !== 'lc0_browser.artifact_release_manifest.v2') throw new Error('A v2 release manifest is required');
    const artifacts = {};
    for (const entry of release.artifacts) {
      if (entry.kind !== 'engine' || !/\.(?:js|wasm|data|nnue)$/.test(entry.logicalUrl)) continue;
      // Drop historical per-variant .data aliases; only canonical paths appear
      // in the engine manifests. Preserve the release's encoded hash verbatim.
      const directory = `public/${entry.logicalUrl.split('/')[1]}`;
      const sourceName = readdirSync(join(ROOT, directory)).find((name) => name.endsWith('.manifest.json'));
      const source = JSON.parse(readFileSync(join(ROOT, directory, sourceName), 'utf8'));
      if (!source.artifacts.some((item) => item.path === `public${entry.logicalUrl}`)) continue;
      const br = entry.representations.find((item) => item.encoding === 'br');
      if (br && new URL(br.url, 'https://assets.0x88.app').pathname !== `/artifacts/sha256/${entry.raw.sha256}/br/${br.sha256}`)
        throw new Error(`Invalid representation URL: ${entry.logicalUrl}`);
      artifacts[entry.logicalUrl] = { raw: entry.raw, ...(br ? { br: { sha256: br.sha256, bytes: br.bytes } } : {}) };
    }
    writeFileSync(
      join(ROOT, REPRESENTATIONS),
      `${JSON.stringify({ source: `/releases/${release.releaseId}.json`, schema: release.schema, artifacts: Object.fromEntries(Object.entries(artifacts).sort(([a], [b]) => a.localeCompare(b))) }, null, 2)}\n`,
    );
  }
  const text = serializePins(enginePins());
  if (process.argv.includes('--check')) {
    if (readFileSync(join(ROOT, OUTPUT), 'utf8') !== text) throw new Error(`${OUTPUT} is stale; run node scripts/write_engine_integrity.mjs`);
    console.log(`${OUTPUT} is up to date`);
  } else writeFileSync(join(ROOT, OUTPUT), text);
}
