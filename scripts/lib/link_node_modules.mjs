import { mkdirSync, readdirSync, realpathSync, symlinkSync } from 'node:fs';
import { join, relative } from 'node:path';

const localEntries = new Set(['$app', '.vite', '.vite-cache', '.vite-temp']);

export function linkNodeModules(source, dest) {
  const entries = readdirSync(source).filter((name) => !localEntries.has(name));
  mkdirSync(dest);
  const from = realpathSync(dest);
  return entries.map((name) => {
    const link = join(dest, name);
    const target = relative(from, join(source, name));
    symlinkSync(target, link);
    return `${link} -> ${target}`;
  });
}
