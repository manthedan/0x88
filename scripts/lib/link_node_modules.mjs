import { existsSync, mkdirSync, readdirSync, readlinkSync, realpathSync, symlinkSync, unlinkSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const localEntries = new Set(['$app', '.vite', '.vite-cache', '.vite-temp']);
const dependencyEntries = (dir) => readdirSync(dir, { withFileTypes: true }).filter(({ name }) => !localEntries.has(name));

function targetsSource(source, from, entry) {
  return entry.isSymbolicLink() && resolve(from, readlinkSync(join(from, entry.name))) === join(source, entry.name);
}

export function hasSharedNodeModuleLinks(source, dest) {
  const from = realpathSync(dest);
  return dependencyEntries(from).some((entry) => targetsSource(source, from, entry));
}

export function linkNodeModules(source, dest, action = 'create') {
  const missing = new Set(dependencyEntries(source).map(({ name }) => name));
  if (action === 'create') mkdirSync(dest);
  const from = realpathSync(dest);
  const created = [];
  const problems = [];
  for (const entry of dependencyEntries(from)) {
    const wanted = missing.delete(entry.name);
    const link = join(dest, entry.name);
    if (!entry.isSymbolicLink() || existsSync(link)) continue;
    if (action === 'check') problems.push(`${link} is dangling`);
    else if (!wanted && targetsSource(source, from, entry)) unlinkSync(link);
  }
  for (const name of missing) {
    const link = join(dest, name);
    if (action === 'check') problems.push(`${link} missing`);
    else {
      const target = relative(from, join(source, name));
      symlinkSync(target, link);
      created.push(`${link} -> ${target}`);
    }
  }
  return { created, problems };
}
